import pandas as pd
import numpy as np

from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_squared_error as MSE
from sklearn.ensemble import RandomForestRegressor

# Read in the data
rental_info = pd.read_csv("rental_info.csv")

# Convert date columns to datetime
rental_info["rental_date"] = pd.to_datetime(rental_info["rental_date"])
rental_info["return_date"] = pd.to_datetime(rental_info["return_date"])

# Create target column
rental_info["rental_length_days"] = (
    rental_info["return_date"] - rental_info["rental_date"]
).dt.days

# Create required dummy columns from special_features
rental_info["deleted_scenes"] = rental_info["special_features"].str.contains(
    "Deleted Scenes"
).astype(int)

rental_info["behind_the_scenes"] = rental_info["special_features"].str.contains(
    "Behind the Scenes"
).astype(int)

# Create feature DataFrame X
# Avoid leakage columns: rental_date, return_date, rental_length_days
# Also avoid original text column: special_features
X = rental_info[
    [
        "amount",
        "amount_2",
        "rental_rate",
        "rental_rate_2",
        "release_year",
        "length",
        "length_2",
        "replacement_cost",
        "NC-17",
        "PG",
        "PG-13",
        "R",
        "deleted_scenes",
        "behind_the_scenes",
    ]
]

# Create target Series y
y = rental_info["rental_length_days"]

# Split data
X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.2,
    random_state=9
)

# Train model
rf = RandomForestRegressor(
    n_estimators=100,
    random_state=9
)

rf.fit(X_train, y_train)

# Predict and evaluate
y_pred = rf.predict(X_test)

best_mse = MSE(y_test, y_pred)
best_model = rf

print("Best MSE:", best_mse)
print("X shape:", X.shape)

